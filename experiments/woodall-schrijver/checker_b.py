"""Checker B: deliberately different algorithms for the same two quantities.

Independence from checker_a.py, on purpose:

  * dicut shores: checker A scans all 2^n vertex subsets and tests
    delta^-(U) = {} directly.  Checker B instead uses the equivalent
    characterisation "U is closed under in-neighbours", i.e. U is a union of
    ancestor-sets anc(v) = { x : x has a directed path to v }, and enumerates
    the down-sets of the reachability preorder by a recursive down-set
    enumeration whose cost is proportional to the NUMBER of down-sets rather
    than to 2^n.  If the two agree on the shore family, an off-by-one in the
    delta^-/delta^+ convention in either would show up immediately.

  * packing: checker A does a recursive branch-and-prune over arcs.  For
    w in {0,1} checker B does a flat itertools.product over all assignments of
    the positive-weight arcs to {member_1, ..., member_k, unused} and tests
    each candidate outright, with no pruning at all.

  * data representation: sets of vertex/arc names rather than integer bitmasks.

Stdlib only; all arithmetic is exact integer arithmetic.
"""

from itertools import product


class InstanceB:
    def __init__(self, vertices, arcs):
        self.V = frozenset(vertices)
        self.A = []
        for k, a in enumerate(arcs):
            t, h, w = a[0], a[1], (a[2] if len(a) > 2 else 1)
            self.A.append((k, t, h, w))
        self.inn = {v: set() for v in self.V}
        for k, t, h, w in self.A:
            self.inn[h].add(t)

    def ancestors(self, v):
        """All x with a directed path x ->* v (v included)."""
        seen = {v}
        stack = [v]
        while stack:
            u = stack.pop()
            for p in self.inn[u]:
                if p not in seen:
                    seen.add(p)
                    stack.append(p)
        return frozenset(seen)

    def shores(self):
        """All U with {} != U != V and no arc entering U, as frozensets.

        U has no entering arc  <=>  every in-neighbour of every u in U is in U
        <=>  U is a union of ancestor-sets.  So the shores are exactly the
        non-trivial unions of the sets anc(v), which we enumerate as the
        down-sets generated by subsets of the anc-generators, closed under
        union, reached by a worklist rather than by scanning 2^n subsets."""
        gens = {self.ancestors(v) for v in self.V}
        closed = set()
        frontier = [frozenset()]
        seen = {frozenset()}
        while frontier:
            U = frontier.pop()
            closed.add(U)
            for g in gens:
                W = U | g
                if W not in seen:
                    seen.add(W)
                    frontier.append(W)
        return {U for U in closed if U and U != self.V}

    def dicut(self, U):
        return frozenset(k for k, t, h, w in self.A if t in U and h not in U)

    def check_no_entering(self, U):
        return not any(t not in U and h in U for k, t, h, w in self.A)

    def all_dicuts(self):
        S = self.shores()
        for U in S:
            assert self.check_no_entering(U)
            assert self.dicut(U), "delta^+ empty on a dicut shore"
        return S, {U: self.dicut(U) for U in S}

    def wt(self, arcset):
        return sum(w for k, t, h, w in self.A if k in arcset)

    def tau(self):
        S, cuts = self.all_dicuts()
        if not S:
            return None
        return min(self.wt(c) for c in cuts.values())

    def nu01(self, kmax):
        """Max w-packing size, for w in {0,1} only, by flat exhaustive product."""
        assert all(w in (0, 1) for _, _, _, w in self.A), "nu01 is for 0/1 weights"
        S, cuts = self.all_dicuts()
        if not S:
            return None
        C = list(cuts.values())
        pos = [k for k, t, h, w in self.A if w == 1]
        best = 0
        for k in range(1, kmax + 1):
            found = False
            # assignment[i] in {0..k}: 0 = unused, j = member j
            for assign in product(range(k + 1), repeat=len(pos)):
                members = [set() for _ in range(k)]
                for arc, a in zip(pos, assign):
                    if a:
                        members[a - 1].add(arc)
                if all(all(m & c for c in C) for m in members):
                    found = True
                    break
            if found:
                best = k
            else:
                break
        return best
