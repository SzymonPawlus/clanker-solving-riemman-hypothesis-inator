"""Mobility of 8-point far configurations in T(3)  (Oler normalisation, separation > 1).

WHY.  Lemma B of the write-up: if a partition of T(3) has  sum_i cap_>(P_i) = 8  then for every
8-point far configuration F and every x in F, the connected component R_F(x) of
   { y in T(3) : |y - x_k| > 1 for all k != x }
is contained in the single piece that contains x.  Chaining these forces the pieces to be unions
of the equivalence classes of the relation generated by "y is reachable from x".  This script
measures those classes by Monte-Carlo: a tagged particle's reachable set.

`numerical` — search only.  Exact certified paths are produced by certify_path.py.
"""
import json, numpy as np

SQ3 = np.sqrt(3.0)
V = np.array([[0.0, 0.0], [3.0, 0.0], [1.5, 1.5 * SQ3]])


def inside(p):
    x, y = p
    return (y >= 0.0) and (y <= SQ3 * x + 1e-15) and (y <= SQ3 * (3.0 - x) + 1e-15)


def ok(P, i, q, sep2):
    if not inside(q):
        return False
    d = P - q
    d2 = np.einsum('ij,ij->i', d, d)
    d2[i] = np.inf
    return bool(np.all(d2 >= sep2))


def init_config(n, sep, rng, tries=200000):
    P = np.zeros((n, 2))
    k = 0
    for _ in range(tries):
        q = rng.uniform([0, 0], [3, 1.5 * SQ3])
        if not inside(q):
            continue
        if k == 0 or np.all(np.linalg.norm(P[:k] - q, axis=1) >= sep):
            P[k] = q; k += 1
            if k == n:
                return P
    return None


def anneal(n, sep, rng, steps=200000):
    """push a random config to pairwise separation >= sep by soft repulsion + projection"""
    P = rng.uniform([0, 0], [3, 1.0], size=(n, 2))
    for i in range(n):
        while not inside(P[i]):
            P[i] = rng.uniform([0, 0], [3, 1.5 * SQ3])
    for it in range(steps):
        d = P[:, None, :] - P[None, :, :]
        dist = np.linalg.norm(d, axis=2) + np.eye(n)
        bad = dist < sep
        if not bad.any():
            return P
        F = np.zeros_like(P)
        for i in range(n):
            for j in range(n):
                if i != j and bad[i, j]:
                    F[i] += (sep - dist[i, j]) * d[i, j] / dist[i, j]
        P = P + 0.3 * F
        for i in range(n):
            P[i] = clip_tri(P[i])
    return P if not (np.linalg.norm(P[:, None, :] - P[None, :, :], axis=2) + 9 * np.eye(n) < sep).any() else None


def clip_tri(p):
    q = p.copy()
    for _ in range(60):
        g = np.array([q[1], SQ3 * q[0] - q[1], SQ3 * (3 - q[0]) - q[1]])
        k = int(np.argmin(g))
        if g[k] >= 0:
            break
        nv = [np.array([0.0, 1.0]), np.array([SQ3, -1.0]), np.array([-SQ3, -1.0])][k]
        q = q - nv * g[k] / (nv @ nv)
    return q


def seed_config(n, rng, seed=5):
    """optimal n-point config of the unit triangle, scaled into T(3), then jittered."""
    import shapes as _s
    S = _s.make_shapes()
    best, P = -1, None
    for sd in (seed, seed + 17, seed + 41):
        v, Q = _s.maximin(S['triangle'], n, restarts=20, seed=sd)
        if v > best:
            best, P = v, Q
    P = 3.0 * P
    return P, 3.0 * best


def run(n=8, sep=1.0 + 1e-4, steps=400000, step=0.02, seed=0):
    rng = np.random.default_rng(seed)
    P, s0 = seed_config(n, rng, seed=5 + seed)
    if s0 < sep:
        raise SystemExit(f'seed separation {s0} < {sep}')
    P = np.array([clip_tri(p) for p in P])
    sep2 = sep * sep
    P0 = P.copy()
    acc = 0
    lo = P.copy(); hi = P.copy()
    trail = [P.copy()]
    for t in range(steps):
        i = int(rng.integers(n))
        q = P[i] + rng.normal(scale=step, size=2)
        if ok(P, i, q, sep2):
            P[i] = q; acc += 1
            lo[i] = np.minimum(lo[i], q); hi[i] = np.maximum(hi[i], q)
        if steps >= 40 and t % (steps // 40) == 0:
            trail.append(P.copy())
    disp = np.linalg.norm(P - P0, axis=1)
    ranges = np.linalg.norm(hi - lo, axis=1)
    return dict(sep=sep, seed_sep=float(s0), acc_rate=acc / steps, final=P.tolist(),
                init=P0.tolist(), max_displacement=float(disp.max()),
                bbox_diag=[float(v) for v in ranges],
                trail=[t.tolist() for t in trail])


if __name__ == '__main__':
    res = {}
    for sep in (1.0 + 1e-4, 1.005, 1.02):
        for seed in (1, 2, 3):
            r = run(sep=sep, seed=seed, steps=2_000_000, step=0.03)
            key = f"sep{sep}_s{seed}"
            res[key] = r
            print(f"{key}: acc={r['acc_rate']:.3f} maxdisp={r['max_displacement']:.4f} "
                  f"per-point wander={['%.3f'%v for v in r['bbox_diag']]}", flush=True)
    json.dump(res, open('out/mobility.json', 'w'))
