"""Equivalence classes of the free-region relation for 8-point far configurations in T(3).

Lemma B (write-up):  if  sum_i cap_>(P_i) = 8  over a partition of T(3), then for every 8-point
far configuration F and every x in F, the whole connected component of x in
   { y : |y - x_k| > 1 for k != x }  lies in the SAME piece as x.
Chaining over all configurations, each piece is a union of classes of the equivalence relation ~
generated by these components.  This script LOWER-BOUNDS the classes by Monte Carlo: a particle
that MC-wanders from z to z' certifies z ~ z' (up to discretisation), so grid cells visited by one
tagged particle in one run are unioned.

`numerical`.  Any class of diameter > 1 forces a piece of capacity >= 2; a class carrying a whole
8-point far configuration kills the method (see write-up Sec.6).
"""
import json, numpy as np
import mobility as MB

SQ3 = np.sqrt(3.0)
H = 0.05                      # grid step


def cell(p):
    return (int(np.floor(p[0] / H)), int(np.floor(p[1] / H)))


class DSU:
    def __init__(self): self.p = {}
    def find(self, a):
        self.p.setdefault(a, a)
        while self.p[a] != a:
            self.p[a] = self.p[self.p[a]]; a = self.p[a]
        return a
    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb: self.p[ra] = rb


def random_config(n, sep, rng, tries=3000):
    """random sequential insertion + soft-repulsion relaxation"""
    for _ in range(tries):
        P = []
        for _ in range(4000):
            q = rng.uniform([0, 0], [3, 1.5 * SQ3])
            if not MB.inside(q):
                continue
            if all(np.linalg.norm(np.array(r) - q) >= sep for r in P):
                P.append(q)
                if len(P) == n:
                    return np.array(P)
    return None


def mc(P, sep, steps, step, rng, dsu):
    sep2 = sep * sep
    n = len(P)
    prev = [cell(P[i]) for i in range(n)]
    for c in prev:
        dsu.find(c)
    for t in range(steps):
        i = int(rng.integers(n))
        q = P[i] + rng.normal(scale=step, size=2)
        if MB.ok(P, i, q, sep2):
            P[i] = q
            c = cell(q)
            dsu.union(prev[i], c)
            prev[i] = c
    return P


if __name__ == '__main__':
    rng = np.random.default_rng(20260826)
    sep = 1.0 + 1e-6
    dsu = DSU()
    got = 0
    for trial in range(400):
        P = random_config(8, sep, rng, tries=40)
        if P is None:
            continue
        got += 1
        mc(P, sep, 120000, 0.04, rng, dsu)
        if got % 5 == 0:
            print('configs used', got, flush=True)
        if got >= 40:
            break
    comps = {}
    for c in list(dsu.p):
        comps.setdefault(dsu.find(c), []).append(c)
    rows = []
    for root, cells in comps.items():
        pts = np.array([[ (i + .5) * H, (j + .5) * H] for i, j in cells])
        d = 0.0
        if len(pts) > 1:
            from scipy.spatial import ConvexHull
            try:
                hull = pts[ConvexHull(pts).vertices]
            except Exception:
                hull = pts
            for a in range(len(hull)):
                for b in range(a + 1, len(hull)):
                    d = max(d, float(np.linalg.norm(hull[a] - hull[b])))
        rows.append(dict(ncells=len(cells), diam=d,
                         centroid=[float(v) for v in pts.mean(axis=0)]))
    rows.sort(key=lambda r: -r['ncells'])
    print('configs used:', got, ' components:', len(rows))
    for r in rows[:12]:
        print(f"  cells={r['ncells']:5d} diam={r['diam']:.3f} centroid={np.round(r['centroid'],2)}")
    json.dump(dict(sep=sep, h=H, configs=got, comps=rows), open('out/classes.json', 'w'), indent=1)
