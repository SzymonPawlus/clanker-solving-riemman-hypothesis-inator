"""Emit the triangular-number reference certificates used to validate the checker.

For a triangular number n = T_k = k(k+1)/2 the optimal packing is the obvious
triangular-lattice one: k rows of unit circles, k in the bottom row down to 1 at the
apex. In the point formulation this is k rows of points at spacing 2, with row j
offset by (1, sqrt(3)) per step, giving

    p(i, j) = (2i + j, j*sqrt(3)),   j = 0..k-1,  i = 0..k-1-j

inside the triangle of side d = 2(k-1), hence s(T_k) = 2(k-1) + 2*sqrt(3).

That matches the table in `problems/circle-packing-equilateral-triangle/README.md`:
s(6) = 4 + 2*sqrt(3) and s(10) = 6 + 2*sqrt(3).

Coordinates are written as exact strings ("sqrt(3)", "2*sqrt(3)"), never decimals.
This generator is *not* on the verification path -- it produces inputs, which the
checker then verifies from scratch.

Run:  uv run python make_certificates.py
"""

from __future__ import annotations

import json
from pathlib import Path

CERT_DIR = Path(__file__).parent / "certificates"


def triangular_points(k: int) -> list[tuple[str, str]]:
    points: list[tuple[str, str]] = []
    for j in range(k):
        y = "0" if j == 0 else ("sqrt(3)" if j == 1 else f"{j}*sqrt(3)")
        for i in range(k - j):
            points.append((str(2 * i + j), y))
    return points


def certificate(k: int) -> dict:
    n = k * (k + 1) // 2
    d = 2 * (k - 1)
    side = "2*sqrt(3)" if d == 0 else f"{d} + 2*sqrt(3)"
    return {
        "n": n,
        "claim": "construction",
        "side_length": side,
        "coordinates": [list(p) for p in triangular_points(k)],
        "coordinate_type": "algebraic",
        "verified_by": "experiments/circle-packing-checker (python -m packcheck)",
        "status": "numerical",
        "beats_record": (
            "no; this reproduces the classical triangular-lattice packing, which "
            "README.md records as optimal for n = 6 (Oler/Groemer 1961) and "
            "n = 10 (Oler/Groemer 1961)"
        ),
        "_note": (
            "Reference fixture for the exact checker (issue #2). Generated by "
            "make_certificates.py; regenerate rather than hand-editing."
        ),
    }


def main() -> None:
    CERT_DIR.mkdir(exist_ok=True)
    for k in (2, 3, 4):
        cert = certificate(k)
        path = CERT_DIR / f"n{cert['n']:03d}-triangular.json"
        path.write_text(json.dumps(cert, indent=2) + "\n")
        print(f"wrote {path} (n = {cert['n']}, s = {cert['side_length']})")


if __name__ == "__main__":
    main()
