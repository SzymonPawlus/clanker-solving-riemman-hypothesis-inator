"""Exact integer geometry for the dyadic triangular subdivision.

The container is the closed equilateral triangle ``T(d)`` with vertices
``A = (0,0)``, ``B = (d,0)``, ``C = (d/2, d*sqrt(3)/2)`` -- the placement fixed by
``problems/circle-packing-equilateral-triangle/RULES.md`` §2.

Subdivide ``T(d)`` recursively: each equilateral triangle splits into four congruent
equilateral triangles of half the side.  Every vertex produced this way lies on the
lattice generated by ``u = (d/2^L)(1, 0)`` and ``v = (d/2^L)(1/2, sqrt(3)/2)``, so a
level-``L`` cell is described by two integers and an orientation:

* ``up(i, j)``   -- vertices ``(i,j)``, ``(i+1,j)``, ``(i,j+1)``
* ``down(i, j)`` -- vertices ``(i+1,j)``, ``(i,j+1)``, ``(i+1,j+1)``

all in level-``L`` lattice coordinates.  The four children of ``up(i,j)`` are
``up(2i,2j)``, ``up(2i+1,2j)``, ``up(2i,2j+1)``, ``down(2i,2j)``; the four children of
``down(i,j)`` are ``down(2i+1,2j)``, ``down(2i,2j+1)``, ``down(2i+1,2j+1)``,
``up(2i+1,2j+1)``.  Children are *closed* and cover the parent, so every point of the
parent lies in at least one child -- which is what makes the branching exhaustive.

**Why there is no floating point here.**  For lattice displacement ``a*u + b*v``,

    |a*u + b*v|^2 = (d/2^L)^2 * (a^2 + a*b + b^2)

because ``|u|=|v|=d/2^L`` and ``u.v = (d/2^L)^2 / 2``.  With ``d = p/q`` rational, the
whole geometry is integer arithmetic: the test "can these two cells hold two points at
distance >= 2?" is

    p^2 * (a^2 + a*b + b^2)  >=  4^(L+1) * q^2

with both sides exact Python ints.  No rounding, no tolerance, no interval needed.
Interval arithmetic enters only in ``caps.py``, to bound the algebraic constants ``d(k)``.
"""

from __future__ import annotations

UP = 0
DOWN = 1

#: A cell: ``(level, orientation, i, j)``.
Cell = tuple[int, int, int, int]

ROOT: Cell = (0, UP, 0, 0)


def vertices(cell: Cell) -> tuple[tuple[int, int], tuple[int, int], tuple[int, int]]:
    """The three lattice vertices of ``cell``, in its own level's coordinates."""
    _, orient, i, j = cell
    if orient == UP:
        return ((i, j), (i + 1, j), (i, j + 1))
    return ((i + 1, j), (i, j + 1), (i + 1, j + 1))


def subdivide(cell: Cell) -> tuple[Cell, Cell, Cell, Cell]:
    """The four congruent children covering ``cell``."""
    level, orient, i, j = cell
    nl = level + 1
    if orient == UP:
        return (
            (nl, UP, 2 * i, 2 * j),
            (nl, UP, 2 * i + 1, 2 * j),
            (nl, UP, 2 * i, 2 * j + 1),
            (nl, DOWN, 2 * i, 2 * j),
        )
    return (
        (nl, DOWN, 2 * i + 1, 2 * j),
        (nl, DOWN, 2 * i, 2 * j + 1),
        (nl, DOWN, 2 * i + 1, 2 * j + 1),
        (nl, UP, 2 * i + 1, 2 * j + 1),
    )


def max_sq_form(cell_a: Cell, cell_b: Cell) -> tuple[int, int]:
    """Return ``(qmax, level)`` with ``max |P-Q|^2 = (d/2^level)^2 * qmax``.

    ``P`` ranges over ``cell_a`` and ``Q`` over ``cell_b``.  The maximum of a convex
    function (squared distance) over a product of convex polygons is attained at a pair of
    vertices, so scanning the nine vertex pairs is exact, not a heuristic.
    """
    la, _, ia, ja = cell_a
    lb, _, ib, jb = cell_b
    level = la if la >= lb else lb
    sa = 1 << (level - la)
    sb = 1 << (level - lb)
    va = [(x * sa, y * sa) for x, y in vertices((la, cell_a[1], ia, ja))]
    vb = [(x * sb, y * sb) for x, y in vertices((lb, cell_b[1], ib, jb))]
    best = 0
    for ax, ay in va:
        for bx, by in vb:
            da = bx - ax
            db = by - ay
            q = da * da + da * db + db * db
            if q > best:
                best = q
    return best, level
