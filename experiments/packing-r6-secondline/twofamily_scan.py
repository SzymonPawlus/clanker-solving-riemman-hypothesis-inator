"""Direct measurement of the TWO-family delta-robust count.

N2(a, delta) = max over lattices L generated by two line families (unit normals n1, n2,
lambda_1(L) >= 1) and over translations, of  |L cap (T(a) (+) P_delta)|,
where P_delta = {x : |x.n1| <= delta, |x.n2| <= delta}.  This is the exact object the
hypothesis (H2-delta) delivers: every point of P is within delta of a line of each family,
the nearest-intersection map is injective, and its image lies in T(a) (+) P_delta.

The sweep is over the two family directions and the two lattice steps along them, with the
Lagrange test lambda_1(L) >= 1 and a covolume cap (a lattice with large covolume cannot hold
many points and is discarded; the cap is reported).

STATUS: numerical (float grid measurement).
"""
import json, math, sys
import numpy as np

SQRT3 = math.sqrt(3.0)
M_EDGES = np.array([[0.0, -1.0], [-SQRT3 / 2, 0.5], [SQRT3 / 2, 0.5]])


def edge_offsets(a, n1, n2, delta):
    """c_e (support of T(a) in m_e) and the outward push w_e from P_delta."""
    A = np.array([n1, n2]).T
    C = np.linalg.solve(A, M_EDGES.T)                 # (2,3)
    w = delta * np.abs(C).sum(axis=0)                 # (3,)
    c = np.array([0.0, 0.0, SQRT3 / 2 * a])           # <x,m_e> <= c_e on T(a)
    return c + w


def lam1(w1, w2):
    """Shortest non-zero vector length of the lattice <w1, w2> (Lagrange reduction)."""
    u, v = np.array(w1, float), np.array(w2, float)
    for _ in range(60):
        if u @ u > v @ v:
            u, v = v, u
        m = round((u @ v) / (u @ u))
        if m == 0:
            break
        v = v - m * u
    return math.sqrt(min(u @ u, v @ v))


def count_max(w1, w2, a, n1, n2, delta, nt=32, margin=3.0):
    cen = np.array([a / 2.0, a / (2.0 * SQRT3)])
    R = a / SQRT3 + margin + np.linalg.norm(w1) + np.linalg.norm(w2)
    Minv = np.linalg.inv(np.array([w1, w2]).T)
    B = int(math.ceil(np.abs(Minv).sum(axis=1).max() * (R + np.linalg.norm(cen)) + 2))
    ii, jj = np.meshgrid(np.arange(-B, B + 1), np.arange(-B, B + 1), indexing="ij")
    V = ii.ravel()[:, None] * np.asarray(w1)[None, :] + jj.ravel()[:, None] * np.asarray(w2)[None, :]
    V = V[((V - cen) ** 2).sum(axis=1) <= R * R]
    rhs = edge_offsets(a, n1, n2, delta)
    s = np.arange(nt) / nt
    S, U = np.meshgrid(s, s, indexing="ij")
    Tg = S.ravel()[:, None] * np.asarray(w1)[None, :] + U.ravel()[:, None] * np.asarray(w2)[None, :]
    best = 0
    CH = max(1, int(3e6 // max(1, len(V))))
    for st in range(0, len(Tg), CH):
        P = V[None, :, :] + Tg[st:st + CH, None, :]   # (t, v, 2)
        ok = np.ones(P.shape[:2], bool)
        for e in range(3):
            ok &= (P @ M_EDGES[e]) <= rhs[e] + 1e-9
        best = max(best, int(ok.sum(axis=1).max()))
    return best


def N2(a, delta, nphi=31, npsi=31, nw=5, wmax=1.6, covol_cap=1.5, nt=36):
    best, arg = 0, None
    for i1 in range(nphi):
        p1 = (math.pi / 3.0) * i1 / (nphi - 1)
        u1 = np.array([math.cos(p1), math.sin(p1)])
        n1 = np.array([-math.sin(p1), math.cos(p1)])
        for i2 in range(npsi):
            p2 = p1 + math.pi * (i2 + 1) / (npsi + 1)
            u2 = np.array([math.cos(p2), math.sin(p2)])
            n2 = np.array([-math.sin(p2), math.cos(p2)])
            sn = abs(u1[0] * u2[1] - u1[1] * u2[0])
            if sn < 1e-6 or 4 * delta >= sn:          # injectivity of p -> pi(p)
                continue
            for a1 in range(nw):
                r1 = 1.0 + (wmax - 1.0) * a1 / (nw - 1)
                for a2 in range(nw):
                    r2 = 1.0 + (wmax - 1.0) * a2 / (nw - 1)
                    w1, w2 = r1 * u1, r2 * u2
                    if r1 * r2 * sn > covol_cap or lam1(w1, w2) < 1.0 - 1e-12:
                        continue
                    c = count_max(w1, w2, a, n1, n2, delta, nt=nt)
                    if c > best:
                        best, arg = c, (math.degrees(p1), math.degrees(p2), r1, r2)
    return best, arg


if __name__ == "__main__":
    a = float(sys.argv[1]) if len(sys.argv) > 1 else 5.99
    eta = 6.0 - a
    rows = []
    for f in (0.0, 1e-9, 1e-6, 1e-4, 0.1, 0.2, 0.3, 0.4, 0.43, 0.45, 0.5, 0.7, 0.9):
        delta = f if f < 1e-3 else f * eta
        c, arg = N2(a, delta)
        rows.append({"a": a, "eta": eta, "delta": delta, "delta_over_eta": delta / eta,
                     "N2": c, "ok_le26": c <= 26, "arg": arg})
        print(json.dumps(rows[-1]), flush=True)
        json.dump(rows, open("out/twofamily_scan_a%g.json" % a, "w"), indent=1)
